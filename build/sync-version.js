// Writes js/version.js from package.json.
//
// The renderer needs to know its own version for the multiplayer version gate
// and the project-file warning. The packaged desktop app can ask the main
// process, but the web build has no such source, so the version is baked in
// here and this script keeps it honest. Run by build:web, so the shipped web
// copy can never disagree with package.json.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;

const out = `// Generated by "npm run sync:version" from package.json. Do not edit by hand.
// The desktop app overrides this with the real packaged version at startup;
// the web build has no such source, so this constant is what it goes by.
const APP_VERSION = ${JSON.stringify(version)};
`;

const dest = path.join(root, 'js', 'version.js');
const prev = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
if (prev !== out) {
  fs.writeFileSync(dest, out);
  console.log('js/version.js -> ' + version);
} else {
  console.log('js/version.js already ' + version);
}
